#!/usr/bin/env python3
"""Write trimmed copies of the cascade noise configs: PubMedQA keeps only the XTTS voice + Whisper
(all three text embedders); ADMEDVoice keeps only Whisper. Nodes whose id contains a dropped token are
removed with every edge touching them. experiment.name is unchanged, so result files keep their names.

Usage (repo root): python3 scripts/rerun/trim_noise_configs.py   -> configs/<name>_trim.yaml
"""
import glob
import re
import yaml

DROP = {
    "pubmed_qa_tts_asr_embed_": ("m4t", "piper", "wav2vec2"),
    "admed_asr_embed_": ("m4t", "wav2vec2", "whisper_lora"),
}

for path in sorted(glob.glob("configs/*_asr_embed_*.yaml")):
    name = path.split("/")[-1][:-5]
    if not re.search(r"(noisy|speedonly|noise_\w+)_cmp$", name):
        continue
    drop = next(v for k, v in DROP.items() if name.startswith(k))
    cfg = yaml.safe_load(open(path))
    nodes = cfg["graph"]["nodes"]
    node_id = lambda n: n if isinstance(n, str) else n["id"]  # noqa: E731
    keep = [n for n in nodes if not any(t in node_id(n) for t in drop)]
    kept = {node_id(n) for n in keep}
    edges = [e for e in cfg["graph"]["edges"] if e["from"] in kept and e["to"] in kept]
    cfg["graph"]["nodes"], cfg["graph"]["edges"] = keep, edges
    out = f"configs/{name}_trim.yaml"
    with open(out, "w") as fh:
        fh.write(f"# AUTO-GENERATED by scripts/rerun/trim_noise_configs.py from {path} (dropped: {', '.join(drop)})\n")
        yaml.safe_dump(cfg, fh, sort_keys=False, allow_unicode=True)
    print(f"{out}: nodes {len(nodes)} -> {len(keep)}, edges -> {len(edges)}")
